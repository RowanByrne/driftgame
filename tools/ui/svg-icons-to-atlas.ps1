<#
.SYNOPSIS
  Turns a folder of SVG glyphs into white PNG masters, one atlas (<= 1024 px), atlas.json, a native-size
  contact sheet and, optionally, a Luau registry (docs/workflow/ART-PIPELINE.md "Icons drawn in code").

.DESCRIPTION
  Each SVG is rendered at -Render px by headless Microsoft Edge (present on every Windows 11 PC, so no
  Python or Node is needed), in a throwaway browser profile. Glyphs become white with their coverage as
  alpha (tinted in game with ImageColor3); -KeepColour keeps the SVG's own colours for illustrations.
  Outputs in -Out:
    png\<name>.png        -Master px white masters (editable source stays the SVG)
    atlas.png             -Cell px cells, -Columns wide (auto: up to 1024 / cell)
    atlas.json            per icon: cell, alpha-cropped offset/size (alpha >= 8, 1 px margin), plus image id
    contact-native.png    every icon at -ContactSizes px on -ContactBackground, then 3x magnified
  After uploading atlas.png, run again with -SetAssetId <id> (no re-render): it writes the id into
  atlas.json and regenerates -Registry. The atlas stays under 1024 px, so Roblox does not rescale it and
  the offsets hold; confirm with DecodeRects.luau anyway.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File tools\ui\svg-icons-to-atlas.ps1 -Svg docs\ui\assets\hud-icons\svg -Out docs\ui\assets\hud-icons
.EXAMPLE
  powershell -ExecutionPolicy Bypass -File tools\ui\svg-icons-to-atlas.ps1 -Out docs\ui\assets\hud-icons -SetAssetId 1234567 -Registry src\Client\UI\IconAtlas.luau
#>
param(
	[string]$Svg,
	[Parameter(Mandatory = $true)][string]$Out,
	[int]$Cell = 128,
	[int]$Columns = 0,
	[int]$Master = 256,
	[int]$Render = 768,
	[object[]]$ContactSizes = @(36, 24),
	[string]$ContactBackground = '#142D32',
	[switch]$KeepColour,
	[string]$SetAssetId,
	[string]$Registry,
	[string]$Edge
)
$ErrorActionPreference = 'Stop'
. "$PSScriptRoot\lib\RobloxUiTools.ps1"

$ContactSizes = @(Split-RuiList $ContactSizes | ForEach-Object { [int]$_ })
$outDir = [IO.Path]::GetFullPath($(if ([IO.Path]::IsPathRooted($Out)) { $Out } else { Join-Path (Get-Location).Path $Out }))
$jsonPath = Join-Path $outDir 'atlas.json'

function Write-Registry($atlas) {
	if (-not $Registry) { return }
	$lines = @(
		"-- Generated by tools/ui/svg-icons-to-atlas.ps1 from $(Split-Path $jsonPath -Leaf). Don't edit by hand; rerun the script.",
		'return {',
		"`tImage = `"$($atlas.image)`",",
		"`tCell = $($atlas.cell),",
		"`tIcons = {"
	)
	foreach ($p in ($atlas.icons.PSObject.Properties | Sort-Object Name)) {
		$v = $p.Value
		$lines += "`t`t[`"$($p.Name)`"] = { Offset = Vector2.new($($v.offset.x), $($v.offset.y)), Size = Vector2.new($($v.size.x), $($v.size.y)) },"
	}
	$lines += "`t},", '}'
	$regPath = [IO.Path]::GetFullPath($(if ([IO.Path]::IsPathRooted($Registry)) { $Registry } else { Join-Path (Get-Location).Path $Registry }))
	[IO.File]::WriteAllText($regPath, (($lines -join "`n") + "`n"), (New-Object System.Text.UTF8Encoding $false))
	Write-Output "registry: $regPath"
}

if ($SetAssetId) {
	if (-not (Test-Path $jsonPath)) { throw "No atlas.json in $outDir; build the atlas first." }
	$atlas = Get-Content $jsonPath -Raw | ConvertFrom-Json
	$atlas.image = if ($SetAssetId -match '^\d+$') { "rbxassetid://$SetAssetId" } else { $SetAssetId }
	[IO.File]::WriteAllText($jsonPath, ($atlas | ConvertTo-Json -Depth 6), (New-Object System.Text.UTF8Encoding $false))
	Write-Output "atlas.json: image = $($atlas.image)"
	Write-Registry $atlas
	return
}

if (-not $Svg) { throw "-Svg <folder of .svg files> is required (or use -SetAssetId)." }
$files = @(Get-ChildItem -LiteralPath $Svg -Filter *.svg -File | Sort-Object Name)
if ($files.Count -eq 0) { throw "No .svg files in $Svg" }
$maxCols = [Math]::Floor(1024 / $Cell)
$cols = if ($Columns -gt 0) { $Columns } else { [Math]::Min($maxCols, [Math]::Ceiling([Math]::Sqrt($files.Count))) }
$rowsN = [Math]::Ceiling($files.Count / $cols)
if ($cols * $Cell -gt 1024 -or $rowsN * $Cell -gt 1024) {
	throw "$($files.Count) icons at $Cell px cells need $($cols * $Cell)x$($rowsN * $Cell); keep the atlas <= 1024 (smaller -Cell, or split the set)."
}

if (-not $Edge) {
	$Edge = @("${env:ProgramFiles(x86)}\Microsoft\Edge\Application\msedge.exe", "$env:ProgramFiles\Microsoft\Edge\Application\msedge.exe") |
		Where-Object { Test-Path $_ } | Select-Object -First 1
}
if (-not $Edge) { throw 'Microsoft Edge not found; pass -Edge <path to msedge.exe>.' }

$tmp = Join-Path ([IO.Path]::GetTempPath()) ('svg-atlas-' + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $tmp, (Join-Path $outDir 'png') -Force | Out-Null
$renders = @{}
try {
	foreach ($f in $files) {
		$name = [IO.Path]::GetFileNameWithoutExtension($f.Name)
		$html = Join-Path $tmp "$name.html"
		$shot = Join-Path $tmp "$name.png"
		$svgUri = ([Uri]$f.FullName).AbsoluteUri
		[IO.File]::WriteAllText($html, "<!doctype html><html><head><style>html,body{margin:0;padding:0;background:transparent;overflow:hidden}img{display:block;width:${Render}px;height:${Render}px}</style></head><body><img src=`"$svgUri`"></body></html>")
		$edgeArgs = @('--headless=new', '--disable-gpu', '--hide-scrollbars', '--no-first-run', '--disable-extensions',
			"--user-data-dir=`"$(Join-Path $tmp 'profile')`"", '--default-background-color=00000000',
			"--window-size=$Render,$Render", "--screenshot=`"$shot`"", "`"$(([Uri]$html).AbsoluteUri)`"")
		$p = Start-Process -FilePath $Edge -ArgumentList $edgeArgs -Wait -PassThru -WindowStyle Hidden
		if (-not (Test-Path $shot)) { throw "Edge produced no render for $($f.Name) (exit $($p.ExitCode))." }
		$bmp = [RobloxUi.ImageOps]::Load($shot)
		if ($bmp.Width -ne $Render -or $bmp.Height -ne $Render) {
			$fixed = [RobloxUi.ImageOps]::Crop($bmp, (New-Object System.Drawing.Rectangle 0, 0, ([Math]::Min($Render, $bmp.Width)), ([Math]::Min($Render, $bmp.Height))))
			$bmp.Dispose(); $bmp = $fixed
		}
		if (-not $KeepColour) {
			if ([RobloxUi.ImageOps]::HasTransparency($bmp)) { [RobloxUi.ImageOps]::Tint($bmp, [System.Drawing.Color]::White) }
			else { [RobloxUi.ImageOps]::CoverageToWhite($bmp) } # opaque white page: dark ink becomes alpha
		}
		$renders[$name] = $bmp
		$m = [RobloxUi.ImageOps]::ResizeHq($bmp, $Master, $Master)
		$m.Save((Join-Path $outDir "png\$name.png"), [System.Drawing.Imaging.ImageFormat]::Png); $m.Dispose()
	}

	$atlasBmp = New-Object System.Drawing.Bitmap ([int]($cols * $Cell)), ([int]($rowsN * $Cell)), ([System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
	$icons = [ordered]@{}
	$i = 0
	foreach ($f in $files) {
		$name = [IO.Path]::GetFileNameWithoutExtension($f.Name)
		$cx = ($i % $cols) * $Cell; $cy = [Math]::Floor($i / $cols) * $Cell
		$cellBmp = [RobloxUi.ImageOps]::ResizeHq($renders[$name], $Cell, $Cell)
		$g = [System.Drawing.Graphics]::FromImage($atlasBmp)
		$g.CompositingMode = [System.Drawing.Drawing2D.CompositingMode]::SourceCopy
		$g.DrawImageUnscaled($cellBmp, [int]$cx, [int]$cy); $g.Dispose()
		$b = [RobloxUi.ImageOps]::AlphaBounds($cellBmp, 8, 1)
		$cellBmp.Dispose()
		if ($b.Empty) { Write-Warning "$name renders empty (check its fill / viewBox)"; $b.X = 0; $b.Y = 0; $b.W = $Cell; $b.H = $Cell }
		$icons[$name] = [ordered]@{ cell = [ordered]@{ x = [int]$cx; y = [int]$cy }; offset = [ordered]@{ x = [int]($cx + $b.X); y = [int]($cy + $b.Y) }; size = [ordered]@{ x = $b.W; y = $b.H } }
		$i++
	}
	$atlasPath = Join-Path $outDir 'atlas.png'
	$atlasBmp.Save($atlasPath, [System.Drawing.Imaging.ImageFormat]::Png)

	# Contact sheet: each icon at its real sizes, cropped from the atlas exactly as the game will draw it.
	$bgc = ConvertTo-RuiColor $ContactBackground
	$tile = ($ContactSizes | Measure-Object -Maximum).Maximum + 12
	$labelW = 140; $perRow = 4
	$cellW = $labelW + $ContactSizes.Count * $tile
	$sheetRows = [Math]::Ceiling($files.Count / $perRow)
	$native = New-Object System.Drawing.Bitmap ([int]($perRow * $cellW)), ([int]($sheetRows * $tile)), ([System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
	$g = [System.Drawing.Graphics]::FromImage($native)
	$font = New-Object System.Drawing.Font 'Segoe UI', 8
	$g.Clear($bgc); $g.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::AntiAliasGridFit
	$i = 0
	foreach ($name in $icons.Keys) {
		$ox = ($i % $perRow) * $cellW; $oy = [Math]::Floor($i / $perRow) * $tile
		$g.DrawString($name, $font, [System.Drawing.Brushes]::Gainsboro, [float]($ox + 4), [float]($oy + $tile / 2 - 7))
		$v = $icons[$name]; $src = New-Object System.Drawing.Rectangle $v.offset.x, $v.offset.y, $v.size.x, $v.size.y
		$x = $ox + $labelW
		foreach ($s in $ContactSizes) {
			$k = [Math]::Min($s / $v.size.x, $s / $v.size.y); $w = $v.size.x * $k; $h = $v.size.y * $k
			[RobloxUi.ImageOps]::DrawHq($g, $atlasBmp, $src, (New-Object System.Drawing.RectangleF ($x + ($tile - $w) / 2), ($oy + ($tile - $h) / 2), $w, $h))
			$x += $tile
		}
		$i++
	}
	$g.Dispose(); $font.Dispose()
	$big = [RobloxUi.ImageOps]::Magnify($native, 3)
	$contactPath = Join-Path $outDir 'contact-native.png'
	$sheet = New-Object System.Drawing.Bitmap $big.Width, ($native.Height + $big.Height + 8), ([System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
	$g = [System.Drawing.Graphics]::FromImage($sheet); $g.Clear([System.Drawing.Color]::FromArgb(255, 24, 24, 24))
	$g.DrawImageUnscaled($native, 0, 0); $g.DrawImageUnscaled($big, 0, $native.Height + 8); $g.Dispose()
	$sheet.Save($contactPath, [System.Drawing.Imaging.ImageFormat]::Png)
	$sheet.Dispose(); $big.Dispose(); $native.Dispose(); $atlasBmp.Dispose()

	$atlas = [ordered]@{
		generator = 'tools/ui/svg-icons-to-atlas.ps1 (headless Edge render)'
		image = $null; cell = $Cell; columns = [int]$cols; size = [ordered]@{ w = [int]($cols * $Cell); h = [int]($rowsN * $Cell) }
		render = $Render; rectPolicy = 'alpha >= 8, 1 px margin, within the cell'; sha256 = Get-RuiSha256 $atlasPath
		icons = $icons
	}
	if (Test-Path $jsonPath) {
		$old = Get-Content $jsonPath -Raw | ConvertFrom-Json
		if ($old.image -and $old.sha256 -eq $atlas.sha256) { $atlas.image = $old.image } # same pixels keep their id
	}
	[IO.File]::WriteAllText($jsonPath, ($atlas | ConvertTo-Json -Depth 6), (New-Object System.Text.UTF8Encoding $false))
	Write-Output "atlas: $atlasPath ($($atlas.size.w)x$($atlas.size.h), $($files.Count) icons, sha256 $($atlas.sha256))"
	Write-Output "json: $jsonPath"
	Write-Output "contact: $contactPath"
	if ($atlas.image) { Write-Registry ([pscustomobject]$atlas | ConvertTo-Json -Depth 6 | ConvertFrom-Json) }
	elseif ($Registry) { Write-Output 'registry: skipped until the atlas is uploaded (rerun with -SetAssetId).' }
} finally {
	foreach ($b in $renders.Values) { $b.Dispose() }
	Remove-Item $tmp -Recurse -Force -ErrorAction SilentlyContinue
}
